// The router's own account of what it serves.
//
// Several things need to know the complete list of routes rather than the ones
// somebody remembered to write down: the API-key allow-list drift tests
// (keyroutes_test.go), the telemetry cardinality tests, and — the reason this
// moved out of _test.go — scripts/zap-scan.sh, which builds its authenticated
// crawl from it. A scanner that is fed a hand-maintained URL list tests the
// list; one fed the router tests the application, and cannot quietly fall
// behind a route added last week.

// Route is one method-and-pattern the platform serves, and which of the two
// listeners serves it.
type Route struct {
	Method  string `json:"method"`
	Pattern string `json:"pattern"`
	// Router is "platform" (the :8080 listener — API and SPA) or "apps" (the
	// APPS_PORT gateway). They are different origins serving different things,
	// so a caller that treats the union as one surface would get the isolation
	// question exactly backwards.
	Router string `json:"router"`
	// Handler is the name of the function that serves it, taken from the
	// handler chi hands the walk — so it is where the route really goes, not
	// where somebody thinks it goes. Source is that function's file and line,
	// relative to the repository root, and is empty when the sources are not
	// on disk.
	//
	// This is what makes a scanner's output actionable. "Medium risk on
	// GET /api/v1/apps/8f3…/logs" is a URL; the same finding with
	// internal/api/log_handlers.go:41 beside it is a thing to go and fix.
	Handler string `json:"handler,omitempty"`
	Source  string `json:"source,omitempty"`
}

// RouterPlatform and RouterApps are the two values of Route.Router.
const (
	RouterPlatform = "platform"
	RouterApps     = "apps"
)

// handlerName is the short name of the function a route is served by.
//
// The handler chi walks is a method value, and the compiler serves those
// through a generated wrapper — so the code pointer names the function
// correctly (…(*Server).handleListApps-fm) and then reports its file as
// "<autogenerated>:1". The name is the part worth keeping; the file comes from
// handlerSources below.
func handlerName(h http.Handler) string {
	v := reflect.ValueOf(h)
	if v.Kind() != reflect.Func {
		// http.HandlerFunc is a func type; anything else is a struct with a
		// ServeHTTP method, and there is no code pointer to take.
		return ""
	}
	fn := runtime.FuncForPC(v.Pointer())
	if fn == nil {
		return ""
	}
	name := fn.Name()
	if i := strings.LastIndex(name, "."); i >= 0 {
		name = name[i+1:]
	}
	return strings.TrimSuffix(name, "-fm")
}

// handlerSources indexes where each handler in this package is defined, by
// reading the package's own source.
//
// Reading .go files at runtime is not a thing a server should do, and this is
// not the server: `toft routes` runs in the checkout it was built from,
// and the whole value of the answer is that it names a file somebody can open.
// When the sources are not there — a binary shipped in an image — every Source
// is simply empty, and the inventory is still complete.
func handlerSources(root string) map[string]string {
	dir := filepath.Join(root, "internal", "api")
	names, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil
	}
	decl := regexp.MustCompile(`^func \((?:\w+ )?\*?Server\) (\w+)\(`)
	sources := map[string]string{}
	for _, path := range names {
		if strings.HasSuffix(path, "_test.go") {
			continue
		}
		body, err := os.ReadFile(path)
		if err != nil {
			continue
		}
		rel := strings.TrimPrefix(path, root)
		for i, line := range strings.Split(string(body), "\n") {
			if m := decl.FindStringSubmatch(line); m != nil {
				sources[m[1]] = fmt.Sprintf("%s:%d", rel, i+1)
			}
		}
	}
	return sources
}

// repoRoot recovers the build-time path of the repository root, so handler
// locations can be reported relative to it.
//
// Derived from this very file rather than from the working directory: the
// command may be run from anywhere, and what is wanted is the checkout this
// binary was built from.
func repoRoot() string {
	_, file, _, ok := runtime.Caller(0) // .../internal/api/routes.go
	if !ok {
		return ""
	}
	return strings.TrimSuffix(file, filepath.Join("internal", "api", "routes.go"))
}

// inventoryRouters builds both routers for enumeration only.
//
// The one construction: RouteInventory below and routerForWalk in the tests
// both come through here, so the list a scanner is handed and the list the
// drift tests certify cannot be built two different ways and disagree.
func inventoryRouters() (platform, apps *chi.Mux, err error) {
	s := &Server{cfg: &config.Config{}}
	platform, ok := s.Router(http.NotFoundHandler()).(*chi.Mux)
	if !ok {
		return nil, nil, fmt.Errorf("the %s router is not a *chi.Mux", RouterPlatform)
	}
	apps, ok = s.AppsRouter().(*chi.Mux)
	if !ok {
		return nil, nil, fmt.Errorf("the %s router is not a *chi.Mux", RouterApps)
	}
	return platform, apps, nil
}

// RouteInventory enumerates every route both listeners serve.
//
// It builds the routers from a bare configuration and never serves a request:
// no database, no JWT service, no secrets. Constructing a router is pure — the
// handlers are method values, not calls — so this is safe to run from a
// subcommand on a machine with no Postgres, which is the whole point of it
// being available outside the test binary.
func RouteInventory() ([]Route, error) {
	platform, apps, err := inventoryRouters()
	if err != nil {
		return nil, err
	}

	root := repoRoot()
	sources := handlerSources(root)

	var routes []Route
	walk := func(name string, mux *chi.Mux) error {
		return chi.Walk(mux, func(method, route string, h http.Handler, _ ...func(http.Handler) http.Handler) error {
			fn := handlerName(h)
			// Normalized through the same function the API-key guard uses, so
			// a caller matching against this list cannot be handed a spelling
			// the runtime would not recognise.
			routes = append(routes, Route{
				Method:  method,
				Pattern: normalizeRoutePattern(route),
				Router:  name,
				Handler: fn,
				Source:  sources[fn],
			})
			return nil
		})
	}

	if err := walk(RouterPlatform, platform); err != nil {
		return nil, err
	}
	if err := walk(RouterApps, apps); err != nil {
		return nil, err
	}

	sort.Slice(routes, func(i, j int) bool {
		a, b := routes[i], routes[j]
		if a.Router != b.Router {
			return a.Router < b.Router
		}
		if a.Pattern != b.Pattern {
			return a.Pattern < b.Pattern
		}
		return a.Method < b.Method
	})
	return routes, nil
}
