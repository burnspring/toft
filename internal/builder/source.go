// AppDir is the root of everything Toft stores for an app.
//
// One member of this path family lives elsewhere: the ephemeral scratch
// directory (apps/<id>/scratch) is runtime.ScratchDir, because the runtime
// owns its lifecycle — this package would need an import cycle to define it
// for the backend that wipes it.
func AppDir(appsDir, appID string) string {
	return filepath.Join(appsDir, appID)
}

// ReleaseDir is the immutable checkout for one deployment. Builds never touch
// the directory a running app is serving from.
func ReleaseDir(appsDir, appID, deploymentID string) string {
	return filepath.Join(appsDir, appID, "releases", deploymentID)
}

// CurrentLink points at the release currently serving traffic. It exists so an
// operator can find the live code without consulting the database.
func CurrentLink(appsDir, appID string) string {
	return filepath.Join(appsDir, appID, "current")
}

// UploadStagingDir is where an uploaded ZIP is extracted before a deployment
// exists to name a release after.
func UploadStagingDir(appsDir, appID string) string {
	return filepath.Join(appsDir, appID, "upload-staging")
}

// EnsureAppDirs creates apps/<id> and apps/<id>/releases with the execute bit
// for everyone (0711): traversal without listing, so the app account can reach
// its release (a 0700 parent makes every spawn fail with EACCES) while no app
// can enumerate another's release IDs or find its upload staging.
//
// This is the permissive floor, not the boundary. Where each app has an account
// of its own, `runtime.gateAppDir` narrows both of these to root-owned 0710
// with that app's own supplementary group at every hand-over, and *that* is
// where per-app secrecy lives. It cannot live on the release directory's 0700,
// which this comment used to say it did: the app owns that directory, so
// clearing the bit is a permitted operation and the parents were traversable by
// every app account by design.
//
// The narrowing is deliberately not done here. This function is called by a
// builder that knows an app id and by a restore that knows even less, and the
// account is resolved from the app's *slug* at spawn — which is also the only
// moment that survives a container replacement reshuffling every UID and GID.
//
// The explicit Chmod, not just MkdirAll, heals trees created before this
// invariant existed — but it must never widen a gated one. A directory that
// already grants traversal is left exactly as it is, so a redeploy or a restore
// cannot reopen apps/<id> to every app account for the seconds between here and
// the spawn that would re-gate it. Healing a 0700 is the case this is for; 0710
// and 0711 both already do the one job this function has.
//
// **APPS_DIR itself is healed too**, for everyone's search bit only. It is the
// level above every app, and on a fresh volume — a replaced instance, a new
// install — something created it 0700 before this ran, so every app account
// was refused its own tree (`venv/bin/python: Permission denied` on trytoft
// after an instance refresh, 2026-10-23) and nothing ever widened it.
func EnsureAppDirs(appsDir, appID string) error {
	if err := os.MkdirAll(appsDir, 0711); err != nil {
		return err
	}
	if err := ensureTraversable(appsDir); err != nil {
		return err
	}
	for _, dir := range []string{
		AppDir(appsDir, appID),
		filepath.Join(appsDir, appID, "releases"),
	} {
		if err := os.MkdirAll(dir, 0711); err != nil {
			return err
		}
		info, err := os.Stat(dir)
		if err != nil {
			return err
		}
		if info.Mode().Perm()&0011 != 0 {
			continue
		}
		if err := os.Chmod(dir, 0711); err != nil {
			return err
		}
	}
	return nil
}

// UploadScheme marks apps whose source arrived as a ZIP rather than a repo.
const UploadScheme = "upload://"

// IsUploadedSource reports whether an app has no remote to clone from.
func IsUploadedSource(repoURL string) bool {
	return strings.HasPrefix(repoURL, UploadScheme)
}

// buildArtifacts are regenerated by every build and are never carried between
// releases: a venv holds absolute paths to the release it was created in, and
// copying node_modules would defeat the lockfile-exact install.
//
// ExcludedDirs plus `.next`, spelled as an explicit union rather than as a
// second list that happens to agree with it. `.next` is here and not there
// because the shared set deliberately holds no build output (see exclude.go);
// this call site is the one place output is known to be regenerable, since
// nothing reaches it that was not built from these same files a release ago.
func buildArtifact(name string, isDir bool) bool {
	return ExcludedNode(name, isDir) || (isDir && name == ".next")
}

// stageUploadedSource populates a release from the upload staging tree without
// consuming it.
//
// The staging tree is the *only* copy of an uploaded app's source: there is no
// repository to clone, and until a release goes live there is no `current` to
// copy from either. Moving it — which this did — made one failed deploy the end
// of the app: the source went into a release that never started, every retry
// reported "No source available", and the archive had to be uploaded again.
// That is the wrong asymmetry. A deploy that fails must leave the source where
// the next attempt finds it, so the tree is copied here and cleared by the
// deploy that reaches a live release, and by nothing else.
func stageUploadedSource(staging, releaseDir string) error {
	if err := os.RemoveAll(releaseDir); err != nil {
		return fmt.Errorf("clearing release directory: %w", err)
	}
	return copyTree(staging, releaseDir)
}

// copyTree copies src to dst, skipping build artifacts. Used to seed a new
// release from the previous one when there is no repository to clone.
//
// src is resolved first: the caller passes the `current` symlink, and the walk
// would otherwise stop at the link itself without descending into the release.
//
// **The tree is read through an os.Root**, for the reason zipTree's is. In the
// shared runtime this process is root and `current` is a release the app's own
// account owns and can rewrite while the walk runs: a type check on the
// listing followed by a path-based open is a race the app wins, and what it
// wins is root copying a file of its choosing — /etc/shadow, another app's
// environment — into the release it is about to be handed. Every directory
// read and file open here resolves inside src and refuses a link that leaves
// it, a file is opened O_NOFOLLOW, and the opened descriptor is checked to be a
// regular file before a byte is copied.
func copyTree(src, dst string) error {
	resolved, err := filepath.EvalSymlinks(src)
	if err != nil {
		return fmt.Errorf("resolving %s: %w", src, err)
	}
	root, err := os.OpenRoot(resolved)
	if err != nil {
		return fmt.Errorf("opening %s: %w", resolved, err)
	}
	defer root.Close()

	return fs.WalkDir(root.FS(), ".", func(rel string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if rel == "." {
			return os.MkdirAll(dst, 0700)
		}
		if buildArtifact(d.Name(), d.IsDir()) {
			if d.IsDir() {
				return fs.SkipDir
			}
			return nil
		}

		target := filepath.Join(dst, filepath.FromSlash(rel))
		switch {
		case d.IsDir():
			info, err := d.Info()
			if err != nil {
				return err
			}
			return os.MkdirAll(target, info.Mode().Perm())
		case !d.Type().IsRegular():
			// Symlinks are not reproduced — a release must be self-contained.
			return nil
		}

		// Non-blocking as well as no-follow: a regular file swapped for a FIFO
		// since the listing held root's open until a writer came, with the
		// build worker and cacheMu's read lock held for ever (code review
		// 2026-11-11, F-11). The IsRegular check on the descriptor below then
		// refuses it like any other non-file.
		in, err := root.OpenFile(rel, os.O_RDONLY|syscall.O_NOFOLLOW|toolchain.OpenNonblock, 0)
		if errors.Is(err, syscall.ELOOP) {
			// A file swapped for a link since the listing: not reproduced,
			// like any other link.
			return nil
		}
		if err != nil {
			return err
		}
		defer in.Close()
		info, err := in.Stat()
		if err != nil {
			return err
		}
		if !info.Mode().IsRegular() {
			return nil
		}
		return copyFrom(in, target, info.Mode().Perm())
	})
}

// copyFrom writes an already-opened source to dst.
func copyFrom(in io.Reader, dst string, mode os.FileMode) error {
	out, err := os.OpenFile(dst, os.O_WRONLY|os.O_CREATE|os.O_TRUNC, mode)
	if err != nil {
		return err
	}
	defer out.Close()

	_, err = io.Copy(out, in)
	return err
}

var branchPattern = regexp.MustCompile(`^[A-Za-z0-9._/-]{1,255}$`)

// ValidateRepoURL rejects anything git would treat as something other than a
// plain remote fetch. Two concrete hazards:
//
//   - a URL beginning with "-" is parsed by git as an option, and options like
//     --upload-pack=<cmd> execute commands;
//   - the ext:: and file:: transports run local commands / read local paths.
func ValidateRepoURL(raw string) error {
	trimmed := strings.TrimSpace(raw)
	if trimmed == "" {
		return fmt.Errorf("repository URL is required")
	}
	if strings.HasPrefix(trimmed, "-") {
		return fmt.Errorf("repository URL may not start with '-'")
	}
	if strings.ContainsAny(trimmed, "\n\r\x00") {
		return fmt.Errorf("repository URL contains control characters")
	}

	parsed, err := url.Parse(trimmed)
	if err != nil {
		return fmt.Errorf("malformed repository URL")
	}
	if parsed.Scheme != "https" {
		return fmt.Errorf("only https:// repository URLs are supported (got %q)", parsed.Scheme)
	}
	if parsed.Host == "" {
		return fmt.Errorf("repository URL has no host")
	}
	if parsed.User != nil {
		return fmt.Errorf("credentials in the repository URL are not supported")
	}
	return nil
}

// ValidateBranch keeps the ref away from git's option parsing and from shell
// metacharacters, without trying to reimplement git-check-ref-format.
func ValidateBranch(branch string) error {
	if branch == "" {
		return fmt.Errorf("branch is required")
	}
	if strings.HasPrefix(branch, "-") {
		return fmt.Errorf("branch may not start with '-'")
	}
	if !branchPattern.MatchString(branch) {
		return fmt.Errorf("branch contains unsupported characters")
	}
	if strings.Contains(branch, "..") {
		return fmt.Errorf("branch may not contain '..'")
	}
	return nil
}

// subdirSegment is one folder name of a repository subdirectory: the branch
// alphabet without the slash, and never starting with '-' so no segment can be
// read as an option by anything that is handed the path.
var subdirSegment = regexp.MustCompile(`^[A-Za-z0-9._][A-Za-z0-9._-]{0,127}$`)

// NormalizeSubdir is the one way a folder a person typed becomes the form that
// is stored: surrounding space and slashes dropped, so `apps/web/` and
// `/apps/web` both name `apps/web`. It does not make a bad path good —
// ValidateSubdir still has to accept the result.
func NormalizeSubdir(s string) string {
	return strings.Trim(strings.TrimSpace(s), "/")
}

// ValidateSubdir accepts the folder of a repository an app is built from.
// Empty is the repository root. Anything else is a clean relative path whose
// every segment is a plain folder name: no `.` or `..`, no `.git`, no
// backslash, nothing absolute, so the folder cannot name anything outside the
// clone it is taken from — PlaceSubdir checks the same on disk, because a
// folder can still be a symlink in the repository itself.
func ValidateSubdir(s string) error {
	if s == "" {
		return nil
	}
	if len(s) > 255 {
		return fmt.Errorf("the folder path is longer than 255 characters")
	}
	if strings.HasPrefix(s, "/") || strings.Contains(s, "\\") {
		return fmt.Errorf("the folder must be a path inside the repository, like apps/web")
	}
	for _, seg := range strings.Split(s, "/") {
		switch {
		case seg == "":
			return fmt.Errorf("the folder path has an empty segment")
		case seg == "." || seg == "..":
			return fmt.Errorf("the folder may not contain . or .. segments")
		case strings.EqualFold(seg, ".git"):
			return fmt.Errorf("the folder may not be inside .git")
		case !subdirSegment.MatchString(seg):
			return fmt.Errorf("the folder %q contains unsupported characters", seg)
		}
	}
	return nil
}

// PlaceSubdir makes cloneDir/subdir the release: it is moved to releaseDir and
// the rest of the clone, .git included, is left for the caller to remove.
//
// Every segment is checked on disk with Lstat rather than trusted from the
// string, because a repository can commit a symlink where a folder is expected
// and a rename would then publish whatever it points at.
func PlaceSubdir(cloneDir, subdir, releaseDir string) error {
	cur := cloneDir
	for _, seg := range strings.Split(subdir, "/") {
		cur = filepath.Join(cur, seg)
		fi, err := os.Lstat(cur)
		if os.IsNotExist(err) {
			return fmt.Errorf("the folder %s is not in the repository", subdir)
		}
		if err != nil {
			return err
		}
		if fi.Mode()&os.ModeSymlink != 0 {
			return fmt.Errorf("the folder %s is a symlink in the repository, which is not followed", subdir)
		}
		if !fi.IsDir() {
			return fmt.Errorf("%s is a file in the repository, not a folder", subdir)
		}
	}
	if err := os.RemoveAll(releaseDir); err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(releaseDir), 0o711); err != nil {
		return err
	}
	return os.Rename(cur, releaseDir)
}

// pruneReleases keeps the newest `keep` successful releases plus the one in
// use, deleting the rest. Errors are non-fatal — a stale release costs disk,
// not correctness.
//
// Only a successful build counts towards `keep`. A failed build's directory is
// not a version — it can never be made current — and counting it is how three
// failed deploys in a row used to push every rollback target off the disk. Its
// directory is removed whatever the count (the builder removes it at failure;
// this catches one left by a crash or by an older binary), and it is reported
// separately because its row stays: a failed build's row is the explanation of
// what went wrong. A directory whose build is still running, or that no row
// accounts for, is left alone.
//
// A release in `pinned` — one an unfinished job run will start from — is
// kept and does not count towards `keep`.
//
// It returns the deployment IDs whose successful releases it removed, because
// the caller deletes their rows too: a build whose code is gone can never be
// made current again, and leaving it in the history is a listing where two rows
// look alike and only one of them means anything.
func pruneReleases(appsDir, appID, keepID string, keep int, status map[string]string, pinned map[string]bool) (pruned, failed []string) {
	dir := filepath.Join(appsDir, appID, "releases")
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, nil
	}

	type rel struct {
		name    string
		modTime int64
	}
	var releases []rel
	for _, e := range entries {
		if !e.IsDir() || e.Name() == keepID || pinned[e.Name()] {
			continue
		}
		switch status[e.Name()] {
		case database.DeployStatusSuccess:
		case database.DeployStatusFailed:
			if os.RemoveAll(filepath.Join(dir, e.Name())) == nil {
				failed = append(failed, e.Name())
			}
			continue
		default:
			continue
		}
		info, err := e.Info()
		if err != nil {
			continue
		}
		releases = append(releases, rel{e.Name(), info.ModTime().UnixNano()})
	}

	// Newest first.
	sort.SliceStable(releases, func(i, j int) bool { return releases[i].modTime > releases[j].modTime })

	// The release in use is one of the `keep`, whichever position it holds.
	if keepID != "" {
		keep--
	}
	for i, r := range releases {
		if i < keep {
			continue
		}
		// Only a release actually removed is reported: a directory that
		// resisted deletion still holds runnable code, and reporting it would
		// have the caller delete the row of a build that is still there.
		if err := os.RemoveAll(filepath.Join(dir, r.name)); err != nil {
			continue
		}
		pruned = append(pruned, r.name)
	}
	return pruned, failed
}

// linkCurrent atomically repoints the `current` symlink at a release.
//
// The target is relative to the link's own directory ("releases/{id}"), so the
// link stays valid whether APPS_DIR is relative or absolute, and survives the
// whole app directory being moved.
func linkCurrent(appsDir, appID, deploymentID string) error {
	link := CurrentLink(appsDir, appID)
	tmp := link + ".tmp"
	os.Remove(tmp)
	if err := os.Symlink(filepath.Join("releases", deploymentID), tmp); err != nil {
		return err
	}
	return os.Rename(tmp, link)
}
