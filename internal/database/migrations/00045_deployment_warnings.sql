-- +goose Up
--
-- What a deploy noticed and carried on past, kept where a client can read it.
--
-- **A warning that only reaches the build log reaches the caller least likely
-- to read one.** `launchpad.toml` deliberately ignores tables its readers do
-- not name — that is what lets an older platform run a newer manifest — and the
-- cost is that a developer can believe they have declared something the
-- platform never saw. A `[tasks]` table where the file wanted `[jobs]` is
-- silently nothing. reconcileManifest already says so, well, in the build log.
--
-- But an agent deploying with `--json` never starts the log follower, and the
-- result object it parses had no field for a warning — so reading it cost a
-- second command (`lp logs --deploy <id>`) after every deploy, on the chance
-- that something was ignored. The reader that most needs the warning was the
-- one that could not see it.
--
-- **On the row, for the reason failure_reason is on the row** (00043). A
-- progress frame is a snapshot: every frame states the deploy in full precisely
-- so a client that reconnects loses nothing. A warning published only on a live
-- frame would be the one thing a reconnecting watcher missed — and the watcher
-- that reconnects is the unattended one.
--
-- It also has to outlive the build log it was also written to. The log is bytes
-- an app's build produced and is subject to retention; "this deploy ignored a
-- table you wrote" is state, and it must still answer afterwards.
--
-- **JSON rather than text[].** The value is a list rendered into a `warnings`
-- array in the deploy result object, and every other structured column here
-- (step_timings, dependency findings) is JSON for the same reason: one encoding
-- between the database and the wire, so nothing has to convert and no
-- conversion can disagree. Empty string means none, which is every row written
-- before this column — never "none were checked".
--
-- No CHECK and no length bound. The warnings are generated by the platform, not
-- submitted, and the manifest reader is what bounds how many there can be.
ALTER TABLE deployments ADD COLUMN warnings text NOT NULL DEFAULT '';

COMMENT ON COLUMN public.deployments.warnings IS 'What this deploy noticed and carried on past, as a JSON array of sentences; rendered into the warnings field of the deploy result object. On the row rather than only on a live progress frame, for the reason failure_reason is: a frame is a snapshot and SnapshotProgress is what a reconnecting watcher receives. Empty means none, which is every row written before this column.';

-- +goose Down
--
-- The column goes, and with it every "this deploy ignored a table you wrote"
-- whose build log has since been trimmed. Nothing is re-derivable: the manifest
-- was read by a build that is no longer running, against a release tree that
-- may no longer exist. A `--json` deploy below this goes back to a result
-- object with no field for a warning, and an ignored table becomes silent again
-- for the reader least able to notice.
ALTER TABLE deployments DROP COLUMN warnings;
