// What goes in the bundle, and what never does.
//
// Four rules, in the order they are applied:
//
//  1. **Everything a `.gitignore` excludes** — every `.gitignore` in the tree,
//     not just the root one, with `!` negations honoured, plus
//     `.git/info/exclude`. That file already says which of these bytes are not
//     the source, and asking people to maintain a second list of the same thing
//     is how the second list goes stale.
//  2. **`.toftignore`**, when present, and it is *additional, never a
//     replacement* — it exists for the file that belongs in the repository and
//     not in a deploy.
//  3. **VCS metadata always**: not needed to build, often the largest thing in
//     the tree, and a working tree carrying a `.git` is how a deployment row
//     comes to claim a commit that is not what is in these files.
//  4. **Build and dependency output always**, `.gitignore` or not — with one
//     condition that is not fussiness, on `dist/` and its siblings. See
//     alwaysExcludedOutput.

// alwaysExcludedVCS is dropped from every bundle, in every tree.
//
// This map and alwaysExcludedDeps below are the CLI's half of one rule the
// server states again in `internal/builder`'s ExcludedDirs, because a second Go
// module cannot import it (ADR §60). `exclude_drift_test.go` over there asserts
// the two agree, so an edit here that is not made there fails the server's
// build — and `alwaysExcludedOutput` is deliberately outside that comparison.
var alwaysExcludedVCS = map[string]bool{
	".git": true,
	".hg":  true,
	".svn": true,
}

// alwaysExcludedDeps are regenerated by the build, are the biggest directories
// in a typical tree, and — in node_modules' case — can carry native binaries
// compiled for the wrong platform, which fails at runtime in a way that is very
// hard to read from a build log.
var alwaysExcludedDeps = map[string]bool{
	"node_modules": true,
	"venv":         true,
	".venv":        true,
	"__pycache__":  true,
}

// alwaysExcludedOutput are dropped **only when the tree root has a
// package.json**, and that condition is load-bearing.
//
// A static site's `dist/` is *the deliverable*, not output: the platform detects
// a folder of HTML as a static app, and nothing in such a tree can rebuild what
// was excluded. Dropping it unconditionally would deploy an empty app and the
// build log would say nothing was wrong. A package.json is the evidence that
// something in the tree knows how to produce these directories again.
var alwaysExcludedOutput = map[string]bool{
	"dist":        true,
	"build":       true,
	"out":         true,
	".next":       true,
	".nuxt":       true,
	".svelte-kit": true,
}

// alwaysExcludedFiles are per-file rather than per-directory. `.git` is here as
// well as in alwaysExcludedVCS: in a git worktree or a submodule it is a file
// naming a local path, which is no more source than the directory form.
var alwaysExcludedFiles = map[string]bool{
	".DS_Store": true,
	".git":      true,
}

// secretish names the files worth a single dimmed line before the upload.
//
// **Not a refusal.** A key or a certificate in the tree is sometimes the
// app's own, and a CLI that refused to deploy them would be wrong more often
// than right. But "I did not know that shipped" is a bad thing to learn later,
// and the one line costs nothing. `.env` is not here: it does not ship at all
// (envFile).
func secretish(name string) bool {
	switch {
	case strings.HasPrefix(name, "id_rsa"), strings.HasPrefix(name, "id_ed25519"):
		return true
	case strings.HasSuffix(name, ".pem"), strings.HasSuffix(name, ".key"):
		return true
	}
	return false
}

// envFile is a dotenv file the bundle never carries, whatever .gitignore or a
// `!` in .toftignore says: `.env` and `.env.<anything>`, except the two
// templates. Nothing on the install reads one — an app's environment is set
// through `toft env` — so its only effect in a bundle was a copy of a
// developer's secrets in a release directory and its archive (ADR §14).
func envFile(name string) bool {
	switch name {
	case ".env.example", ".env.sample":
		return false
	}
	return name == ".env" || strings.HasPrefix(name, ".env.")
}

// File is one entry that made it into the bundle.
type File struct {
	// Rel is the path inside the archive, slash-separated.
	Rel  string
	Size int64
}

// Result is what was built and what the caller should say about it.
type Result struct {
	// Path is the archive on disk. The caller deletes it.
	Path string
	// Files are the entries, largest first — so "the bundle is too big" can be
	// answered with the five paths that made it so, which is nearly always one
	// directory nobody meant to include.
	Files []File
	// Bytes is the uncompressed total, which is the figure a person recognises
	// as "the size of my project".
	Bytes int64
	// Secrets are bundled paths that look like credentials.
	Secrets []string
	// EnvFiles are the dotenv files left out (envFile), so the caller can say
	// where their values go instead.
	EnvFiles []string
	// WorkspaceLeftOut are directories the root go.work uses that exist here
	// and shipped nothing — the build cannot load them (workspaceDirsLeftOut).
	WorkspaceLeftOut []string
}

// Options are the parts of the decision that come from outside this package.
type Options struct {
	// KeepPaths are paths the always-excluded lists must yield to: a
	// `[static] root` in toft.toml that points inside `dist/`, and any `!`
	// negation in `.toftignore`. Without this, a static site declaring its
	// own build output as its root would deploy nothing.
	KeepPaths []string
}

// NotADirectoryError is a bundle asked of something that is not a directory —
// a typo, usually, and the caller's to fix: exit 2, never a failed deploy.
type NotADirectoryError struct{ Dir string }

func (e *NotADirectoryError) Error() string { return e.Dir + " is not a directory" }

// Build walks dir and writes a zip of what should be deployed.
func Build(dir string, opts Options) (*Result, error) {
	root, err := filepath.Abs(dir)
	if err != nil {
		return nil, err
	}
	if info, err := os.Stat(root); err != nil || !info.IsDir() {
		return nil, &NotADirectoryError{Dir: dir}
	}

	m := &Matcher{}
	// `.git/info/exclude` is a real ignore file that no `.gitignore` in the
	// tree mentions, and it is where people put the things they will not commit
	// a rule about.
	if exclude := gitExcludeFile(root); exclude != "" {
		if err := m.AddFile("", exclude); err != nil {
			return nil, err
		}
	}
	if err := m.AddFile("", filepath.Join(root, ".gitignore")); err != nil {
		return nil, err
	}
	if err := m.AddFile("", filepath.Join(root, ".toftignore")); err != nil {
		return nil, err
	}

	hasPackageJSON := fileExists(filepath.Join(root, "package.json"))
	roots, ancestors := normalizeKeep(opts.KeepPaths)

	archive, err := os.CreateTemp("", "toft-deploy-*.zip")
	if err != nil {
		return nil, err
	}
	zw := zip.NewWriter(archive)
	result := &Result{Path: archive.Name()}

	err = walk(root, "", m, false, walkContext{
		root:           root,
		hasPackageJSON: hasPackageJSON,
		roots:          roots,
		ancestors:      ancestors,
		zw:             zw,
		result:         result,
	})
	if err != nil {
		zw.Close()
		archive.Close()
		os.Remove(archive.Name())
		return nil, err
	}
	if err := zw.Close(); err != nil {
		archive.Close()
		os.Remove(archive.Name())
		return nil, err
	}
	if err := archive.Close(); err != nil {
		os.Remove(archive.Name())
		return nil, err
	}

	sort.Slice(result.Files, func(i, j int) bool { return result.Files[i].Size > result.Files[j].Size })
	result.WorkspaceLeftOut = workspaceDirsLeftOut(root, result.Files)
	return result, nil
}

type walkContext struct {
	root           string
	hasPackageJSON bool
	// roots are the declared `[static] root` paths — the deliverable, whose
	// whole subtree ships. ancestors are their proper prefixes, which the walk
	// must enter to reach a root and which are *not* the deliverable: under
	// `frontend/dist`, `frontend/` is still walked under the normal rules
	// (security review 2026-11-14, CS-3).
	roots     map[string]bool
	ancestors map[string]bool
	zw        *zip.Writer
	result    *Result
}

// walk descends one directory, reading the `.gitignore` it finds there first so
// that a nested file's patterns apply to its own subtree — which is the whole
// reason this is a recursive walk rather than a filepath.WalkDir.
//
// onlyToRoot is set inside an ancestor of a declared root that would itself
// have been excluded: such a directory is entered only to reach the root, so
// nothing in it but further ancestors and the root itself is taken. Without
// it, `build/other/` would ship when `build/` is ignored and the root is
// `build/site`, because the matcher excludes a directory's children by pruning
// the directory, not by matching each child.
func walk(dirAbs, rel string, parent *Matcher, onlyToRoot bool, ctx walkContext) error {
	m := parent
	if rel != "" {
		// A copy, so a nested .gitignore's patterns do not leak sideways into a
		// sibling directory that has none.
		m = &Matcher{patterns: append([]pattern(nil), parent.patterns...)}
		if err := m.AddFile(rel, filepath.Join(dirAbs, ".gitignore")); err != nil {
			return err
		}
		if err := m.AddFile(rel, filepath.Join(dirAbs, ".toftignore")); err != nil {
			return err
		}
	}

	entries, err := os.ReadDir(dirAbs)
	if err != nil {
		return err
	}
	for _, entry := range entries {
		name := entry.Name()
		childRel := name
		if rel != "" {
			childRel = rel + "/" + name
		}
		isDir := entry.IsDir()

		// A symlink is followed for its type but never descended into: a link
		// out of the tree is a way to bundle somebody's home directory, and a
		// link back into it is a way to bundle it twice.
		if entry.Type()&os.ModeSymlink != 0 {
			continue
		}

		isRoot, isAncestor := ctx.roots[childRel], ctx.ancestors[childRel]
		if onlyToRoot && !isRoot && !isAncestor {
			continue
		}
		if !isDir && envFile(name) {
			ctx.result.EnvFiles = append(ctx.result.EnvFiles, childRel)
			continue
		}
		childOnlyToRoot := false
		switch {
		case isRoot:
			// The declared root is exempt from both lists.
		case isAncestor:
			// Exempt too, so the walk can reach the root — but one that would
			// have been excluded on its own is entered only for that.
			childOnlyToRoot = onlyToRoot ||
				excludedAlways(name, isDir, ctx.hasPackageJSON) || m.Excluded(childRel, isDir)
		case keptUnder(ctx.roots, childRel):
			// Under a kept root — a declared `[static] root`, the deliverable
			// itself — only version control is still left out: a built site
			// whose page lives at dist/docs/build/ shipped without that page,
			// because `build` is on the always-list for a tree with a
			// package.json (code review 2026-11-11, L-2).
			if excludedVCS(name, isDir) {
				continue
			}
		default:
			if excludedAlways(name, isDir, ctx.hasPackageJSON) || m.Excluded(childRel, isDir) {
				continue
			}
		}

		if isDir {
			if err := walk(filepath.Join(dirAbs, name), childRel, m, childOnlyToRoot, ctx); err != nil {
				return err
			}
			continue
		}
		if err := addFile(filepath.Join(dirAbs, name), childRel, entry, ctx); err != nil {
			return err
		}
	}
	return nil
}

func addFile(abs, rel string, entry os.DirEntry, ctx walkContext) error {
	info, err := entry.Info()
	if err != nil {
		return err
	}
	if !info.Mode().IsRegular() {
		return nil
	}

	header, err := zip.FileInfoHeader(info)
	if err != nil {
		return err
	}
	header.Name = rel
	header.Method = zip.Deflate
	w, err := ctx.zw.CreateHeader(header)
	if err != nil {
		return err
	}
	f, err := os.Open(abs)
	if err != nil {
		return err
	}
	defer f.Close()
	if _, err := io.Copy(w, f); err != nil {
		return err
	}

	ctx.result.Files = append(ctx.result.Files, File{Rel: rel, Size: info.Size()})
	ctx.result.Bytes += info.Size()
	if secretish(path.Base(rel)) {
		ctx.result.Secrets = append(ctx.result.Secrets, rel)
	}
	return nil
}

// excludedVCS is version control metadata, which leaves even a declared
// static root.
func excludedVCS(name string, isDir bool) bool {
	if isDir {
		return alwaysExcludedVCS[name]
	}
	return name == ".git"
}

// gitExcludeFile is the path of the `info/exclude` that applies to the tree at
// root, worked out without running git (the bundle rule: git is never shelled
// out to). In an ordinary checkout it is `.git/info/exclude`. In a worktree or a
// submodule `.git` is a file holding `gitdir: <path>`; a worktree's gitdir has a
// `commondir` naming the main repository's, whose exclude file it shares, and a
// submodule's gitdir has its own. Any read failure means no exclude file, which
// AddFile treats as absent.
func gitExcludeFile(root string) string {
	dotGit := filepath.Join(root, ".git")
	info, err := os.Lstat(dotGit)
	if err != nil || info.IsDir() || !info.Mode().IsRegular() {
		return filepath.Join(dotGit, "info", "exclude")
	}
	raw, err := os.ReadFile(dotGit)
	if err != nil {
		return ""
	}
	line, _, _ := strings.Cut(string(raw), "\n")
	gitdir, ok := strings.CutPrefix(strings.TrimSpace(line), "gitdir:")
	gitdir = strings.TrimSpace(gitdir)
	if !ok || gitdir == "" {
		return ""
	}
	if !filepath.IsAbs(gitdir) {
		gitdir = filepath.Join(root, gitdir)
	}
	if common, err := os.ReadFile(filepath.Join(gitdir, "commondir")); err == nil {
		dir := strings.TrimSpace(string(common))
		if dir == "" {
			return ""
		}
		if !filepath.IsAbs(dir) {
			dir = filepath.Join(gitdir, dir)
		}
		return filepath.Join(dir, "info", "exclude")
	}
	return filepath.Join(gitdir, "info", "exclude")
}

// excludedAlways is the list that does not consult .gitignore at all.
func excludedAlways(name string, isDir, hasPackageJSON bool) bool {
	if isDir {
		if alwaysExcludedVCS[name] || alwaysExcludedDeps[name] {
			return true
		}
		return hasPackageJSON && alwaysExcludedOutput[name]
	}
	if alwaysExcludedFiles[name] {
		return true
	}
	return strings.HasSuffix(name, ".pyc")
}

// normalizeKeep splits the caller's paths into the declared roots and their
// proper ancestors. The walk has to enter `dist` to reach `dist/site`, but only
// the root is the deliverable: an ancestor in the same map as its root made
// everything under `frontend/` skip every exclusion when the root was
// `frontend/dist` (security review 2026-11-14, CS-3).
func normalizeKeep(paths []string) (roots, ancestors map[string]bool) {
	roots, ancestors = map[string]bool{}, map[string]bool{}
	for _, p := range paths {
		p = strings.Trim(strings.ReplaceAll(filepath.Clean(p), string(filepath.Separator), "/"), "/")
		if p == "" || p == "." {
			continue
		}
		roots[p] = true
		for {
			i := strings.LastIndex(p, "/")
			if i < 0 {
				break
			}
			p = p[:i]
			ancestors[p] = true
		}
	}
	// A root is never only an ancestor, and nor is anything already inside
	// another root: that is the deliverable, walked whole.
	for p := range ancestors {
		if roots[p] || keptUnder(roots, p) {
			delete(ancestors, p)
		}
	}
	return roots, ancestors
}

// keptUnder reports whether this path is inside a declared root — the
// descendants of a `[static] root`, which is the deliverable itself.
func keptUnder(roots map[string]bool, rel string) bool {
	for p := range roots {
		if strings.HasPrefix(rel, p+"/") {
			return true
		}
	}
	return false
}

func fileExists(p string) bool {
	_, err := os.Stat(p)
	return err == nil
}
